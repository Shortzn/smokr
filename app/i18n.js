  const DICTS = { en, de, ja };

  function pick(preferred, stored) {
    if (stored && LANGS.includes(stored)) return stored;
    for (const l of preferred || []) {
      const base = String(l).toLowerCase().slice(0, 2);
      if (base === "de" || base === "ja") return base;
      if (base === "en") return "en";
    }
    return "en";
  }

  function make(lang) {
    const dict = DICTS[lang] || en;
    const t = (key, vars) => {
      let s = dict[key];
      if (s == null) s = en[key];
      if (s == null) return key;
      if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? "" : String(vars[k])));
      return s;
    };
    t.lang = lang;
    t.locale = { en: "en-GB", de: "de-AT", ja: "ja-JP" }[lang] || "en-GB";
    return t;
  }

  return { LANGS, DICTS, pick, make };
